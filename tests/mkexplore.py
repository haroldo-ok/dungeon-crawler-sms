#!/usr/bin/env python3
"""Generate tests/explore.txt: a controller-only walk from the start cell into
the open-sky courtyard, one action at a time (press 4 frames, release, wait)."""
route = [("up", 5), ("left", 1), ("up", 5), ("left", 1), ("up", 2), ("right", 1),
         ("up", 2), ("right", 1), ("up", 2)]
out = ["# generated by tests/mkexplore.py", "symbols dungeon.noi", "poke 0xDAF0 23", "poke 0xDAF1 90",
       "waituntil game_ready == 1 3000 w1", "waituntil frames_rendered >= 1 600",
       "poke ai_off 1 w1", "expectvdp display 1",
       "expect px == 1 w1", "expect py == 1 w1", "expect pf == 2 w1"]
moves = turns = 0
for btn, n in route:
    for _ in range(n):
        out += [f"hold {btn}", "run 4", "hold none"]
        if btn == "up":
            moves += 1
            out.append(f"waituntil moves >= {moves} 3000")
        else:
            turns += 1
            out.append(f"waituntil turns >= {turns} 3000")
        out.append("waituntil anim_pos >= 1 3000 w1")
        out.append("run 120")
out += ["echo in the courtyard (open sky)",
        "expect px == 8 w1", "expect py == 6 w1", "expect pf == 2 w1",
        "expect shown_cx == 8 w1", "expect shown_cy == 6 w1", "expect shown_pose == 0 w1",
        "expect bumps == 0",
        "expectcolors 12", "screenshot shots/explore_courtyard.ppm",
        "echo walking into the hedge bumps",
        "hold up", "run 4", "hold none", "run 200",
        "expect py == 7 w1",
        "hold up", "run 4", "hold none", "run 200",
        "expect py == 7 w1", "expect bumps == 1",
        "echo step mode is toggled with L/R while the automap is open",
        "hold 2", "run 4", "hold none", "run 30", "hold 1", "run 4", "hold none", "run 200", "expect map_open == 1 w1",
        "hold right", "run 4", "hold none", "run 30", "expect quick_mode == 1 w1",
        "hold 2", "run 4", "hold none", "run 200", "expect map_open == 0 w1",
        "hold 1+left", "run 4", "hold none", "run 200",
        "expect px == 9 w1",
        "expectpace 0"]
open("tests/explore.txt", "w").write("\n".join(out) + "\n")
