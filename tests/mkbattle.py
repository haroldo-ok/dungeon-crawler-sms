#!/usr/bin/env python3
"""Generate tests/battle.txt: battle mechanics with the normal hero (only the
message pause is shortened).  Fights are started by walking into monsters."""
L = ["# generated by tests/mkbattle.py", "symbols dungeon.noi", "poke 0xDAF0 23", "poke 0xDAF1 90",
     "waituntil game_ready == 1 3000 w1", "waituntil frames_rendered >= 1 600",
     "poke ai_off 1 w1", "poke bt_say_frames 6 w1"]


def press(btn, after=40):
    L.extend([f"hold {btn}", "run 4", "hold none", f"run {after}"])


def tele(x, y, f):
    L.extend([f"poke px {x} w1", f"poke py {y} w1", f"poke pf {f} w1"])


def start_battle():
    press("up", 0)
    L.extend(["waituntil in_battle == 1 600 w1", "run 150"])


# 1. two skeletons with normal stats: FIGHT until the battle ends
L.append("echo 1. FIGHT two skeletons at level 1 with a long sword and leather")
L += ["poke weapon 2 w1", "poke armor 1 w1"]
tele(10, 11, 1)
start_battle()
L += ["expect e_n == 2 w1", "expect shown_pose == 128 w1", "screenshot shots/bt_skel.ppm"]
for _ in range(12):                       # FIGHT + target, repeated (extra presses are harmless)
    press("1", 30)
    press("1", 200)
L += ["waituntil in_battle == 0 3000 w1", "expect bt_result == 1 w1", "expect kills == 2",
      "expect xp == 18", "expect gold == 12", "expect plv == 2 w1", "expect maxhp == 30 w1",
      "expect patk == 8 w1", "expect hp > 0 w1", "run 200"]

# 2. heal + potion inside a fight with three bats; then FIRE
L.append("echo 2. HEAL, POTION and FIRE against three bats")
L += ["poke hp 5 w1", "poke items+0 2 w1"]
tele(9, 7, 1)
start_battle()
L += ["expect e_n == 3 w1", "screenshot shots/bt_bats.ppm"]
press("right", 20); press("1", 20); press("1", 300)            # MAGIC > HEAL
L += ["expect mp == 6 w1", "expect hp > 5 w1"]
press("right", 20); press("right", 20); press("1", 30); press("1", 300)   # ITEM > POTION
L += ["expect items+0 == 1 w1"]
press("right", 20); press("1", 20); press("right", 20); press("1", 20)   # MAGIC > FIRE
L += ["screenshot shots/bt_target.ppm"]
press("1", 300)                                                 # target
L += ["expect mp == 4 w1", "expect kills == 3"]
for _ in range(8):
    press("1", 30)
    press("1", 200)
L += ["waituntil in_battle == 0 3000 w1", "expect bt_result == 1 w1", "expect kills == 5", "run 200"]

# 3. running away leaves the monster stunned where it was
L.append("echo 3. RUN from a skeleton")
L += ["poke hp 30 w1"]
tele(5, 13, 1)
start_battle()
for _ in range(10):
    press("left", 20)                    # wrap to RUN
    press("1", 250)
L += ["waituntil in_battle == 0 3000 w1", "expect bt_result == 2 w1", "run 200"]

# 4. defeat and restart
L.append("echo 4. defeat")
L += ["poke hp 1 w1", "poke pdef 0 w1", "poke patk 1 w1"]
tele(5, 13, 1)
start_battle()
press("1", 400)
L += ["waituntil dead == 1 2000 w1", "expect bt_result == 3 w1", "expect in_battle == 0 w1",
      "screenshot shots/bt_dead.ppm"]
press("1", 300)
L += ["expect dead == 0 w1", "expect hp == 24 w1", "expect plv == 1 w1", "expect px == 1 w1",
      "expectpace 0"]
open("tests/battle.txt", "w").write("\n".join(L) + "\n")
