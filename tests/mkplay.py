#!/usr/bin/env python3
"""Generate tests/playthrough.txt: the whole quest driven only by the pad.
Monster AI is frozen and the hero is boosted so the route is deterministic;
monsters standing on the route are fought (FIGHT, or FIRE against ghosts).
Battle mechanics themselves are tested in tests/battle.txt.
Route: secret wall -> key -> locked door -> stairs -> crypt -> crown."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "tools"))
sys.argv = [sys.argv[0], "/tmp/_gen_unused"]
import gen                                       # level data (objects)
DX, DY = [0, 1, 0, -1], [-1, 0, 1, 0]
monsters = {}                                    # (level, x, y) -> (kind, n)
for li, L in enumerate(gen.LEVELS):
    for k, x, y, n in L["objects"]:
        if k in ("SKEL", "BAT", "GHOST", "SPIDER", "LICH"):
            monsters[(li, x, y)] = (k, n)
cur_level = [0]
lines = ["# generated by tests/mkplay.py", "symbols dungeon.noi", "poke 0xDAF0 23", "poke 0xDAF1 90",
         "waituntil game_ready == 1 3000 w1", "waituntil frames_rendered >= 1 600",
         "poke ai_off 1 w1", "poke quick_mode 1 w1", "poke bt_say_frames 4 w1",
         "poke patk 60 w1", "poke maxhp 99 w1", "poke hp 99 w1", "poke maxmp 99 w1", "poke mp 99 w1"]
st_battles = [0]
st = {"x": 1, "y": 1, "f": 2, "moves": 0, "turns": 0, "uses": 0}


def act(btn, counter):
    st[counter] += 1
    lines.extend([f"hold {btn}", "run 4", "hold none",
                  f"waituntil {counter} >= {st[counter]} 2000", "run 90"])


def face(f):
    while st["f"] != f:
        if (st["f"] + 1) & 3 == f:
            act("right", "turns"); st["f"] = f
        else:
            act("left", "turns"); st["f"] = (st["f"] - 1) & 3


def go(x, y):
    """walk in a straight line to x,y"""
    while (st["x"], st["y"]) != (x, y):
        f = 1 if x > st["x"] else 3 if x < st["x"] else 2 if y > st["y"] else 0
        face(f)
        key = (cur_level[0], st["x"] + DX[f], st["y"] + DY[f])
        if key in monsters:
            fight(*monsters.pop(key))
        act("up", "moves")
        st["x"] += DX[f]; st["y"] += DY[f]


def press(btn, after):
    lines.extend([f"hold {btn}", "run 4", "hold none", f"run {after}"])


def fight(kind, n):
    """walk into the monster group, then defeat it one enemy at a time"""
    st_battles[0] += 1
    lines.append(f"echo battle: {n} x {kind}")
    lines.extend(["hold up", "run 4", "hold none", "waituntil in_battle == 1 600 w1", "run 60"])
    for _ in range(n):
        if kind == "GHOST":
            press("right", 20)          # MAGIC
            press("1", 20)
            press("right", 20)          # FIRE (ghosts take double)
            press("1", 30)
            if n > 1:
                press("1", 30)          # target
            lines.append("run 200")
            press("1", 30)              # FIGHT finishes it off if it survived
                                        # (a harmless "use" if the battle is over)
        elif kind == "LICH":
            for _ in range(4):          # a boss takes a few hits
                press("1", 30)
                lines.append("run 300")
        else:
            press("1", 30)              # FIGHT
        if n > 1:
            press("1", 30)              # target
        lines.append("run 200")
    lines.extend(["waituntil in_battle == 0 900 w1", "expect bt_result == 1 w1", "run 120"])


def path(*pts):
    for p in pts:
        go(*p)
    lines.extend([f"expect px == {st['x']} w1", f"expect py == {st['y']} w1"])


def walk_to(tx, ty):
    """shortest path on the current level (doors count as open: open them first)"""
    m = gen.LEVELS[cur_level[0]]["map"]
    ok = lambda x, y: m[y][x] in ".,:=-" or m[y][x] in "D"
    prev = {(st["x"], st["y"]): None}
    q = [(st["x"], st["y"])]
    while q:
        c = q.pop(0)
        if c == (tx, ty):
            break
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (c[0] + dx, c[1] + dy)
            if n not in prev and ok(*n):
                prev[n] = c
                q.append(n)
    cells, c = [], (tx, ty)
    while c != (st["x"], st["y"]):
        cells.append(c)
        c = prev[c]
    for c in reversed(cells):
        go(*c)
    lines.extend([f"expect px == {st['x']} w1", f"expect py == {st['y']} w1"])


def use(f):
    face(f)
    act("1", "uses")


path((1, 6), (6, 6), (6, 4), (7, 4), (7, 1), (10, 1), (10, 5), (12, 5))
lines.append("echo at the hollow wall: open the secret passage")
use(1)
lines += ["screenshot shots/play_secret.ppm"]
path((13, 5), (13, 1), (14, 1))
lines += ["echo key chamber", "expect nkeys == 1 w1", "screenshot shots/play_key.ppm"]
path((13, 1), (13, 5), (12, 5), (10, 5), (10, 1), (7, 1), (7, 4), (8, 4), (8, 7),
     (9, 7), (9, 11), (9, 13), (12, 13), (12, 14), (13, 14))
lines.append("echo the locked door")
use(1)
lines += ["expect nkeys == 0 w1"]
path((14, 14))
lines.append("echo down the stairs")
face(2)
st["moves"] += 1
cur_level[0] = 1
lines += ["hold up", "run 4", "hold none", f"waituntil level == 1 2000 w1", "run 120",
          "expect level == 1 w1", "expect px == 14 w1", "expect py == 14 w1", "expect pf == 0 w1",
          "screenshot shots/play_crypt.ppm"]
st.update(x=14, y=14, f=0)
path((14, 7), (10, 7), (10, 3), (12, 3))
lines.append("echo down to the catacombs")
face(0)
cur_level[0] = 2
lines += ["hold up", "run 4", "hold none", "waituntil level == 2 2000 w1", "run 120",
          "expect px == 13 w1", "expect py == 13 w1", "expect pf == 3 w1", "screenshot shots/play_catacombs.ppm"]
st.update(x=13, y=13, f=3)
walk_to(5, 2)
lines.append("echo the boss door")
use(3)
walk_to(1, 2)                     # through the Lich King to the crown
lines += ["echo the crown and the ending", "waituntil in_ending == 1 6000 w1", "expect music_cur == 8 w1",
          "run 600", "screenshot shots/play_ending.ppm"]
lines += ["hold 1", "run 4", "hold none", "run 300",
          "expect ending_seen == 1 w1", "expect in_title == 0 w1", f"expect kills >= {st_battles[0]}", "screenshot shots/play_win.ppm",
          "echo automap", "hold 2", "run 4", "hold none", "run 30", "hold 1", "run 4", "hold none", "run 200", "expect map_open == 1 w1",
          "expect shown_pose == 255 w1", "screenshot shots/play_map.ppm",
          "hold 2", "run 4", "hold none", "run 200", "expect map_open == 0 w1", "expect shown_pose == 0 w1",
          "expectpace 0"]
open("tests/playthrough.txt", "w").write("\n".join(lines) + "\n")
print(len(lines), "lines")
