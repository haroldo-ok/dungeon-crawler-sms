#!/usr/bin/env python3
"""Tiny music compiler for the SMS Dungeon PSG driver (src/core.c).

Each song has a tempo (frames per tick) and two voices, written as
"NOTE:TICKS" tokens, e.g. "A4:4 C5:2 r:4".  Bars ('|') are ignored.
Output: gen/music.c (bank 0, read from the VBlank interrupt) + gen/music.h.

Stream bytes: 1..63 = note (index into the period table) followed by a
duration byte; 0x40 = rest + duration; 0xFF = loop to start; 0xFE = end.
"""
import os, sys

OUT = sys.argv[1] if len(sys.argv) > 1 else "gen"
CLOCK = 3579545
LOW_MIDI = 45                      # A2: the lowest note a 10-bit PSG period reaches
NAMES = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}


def midi(tok):
    n = NAMES[tok[0]]
    i = 1
    while tok[i] in '#b':
        n += 1 if tok[i] == '#' else -1
        i += 1
    return 12 * (int(tok[i:]) + 1) + n


def compile_voice(text, loop):
    out = []
    for tok in text.replace('|', ' ').split():
        note, ticks = tok.split(':')
        ticks = int(ticks)
        assert 1 <= ticks <= 255, tok
        if note == 'r':
            out += [0x40, ticks]
        else:
            m = midi(note)
            idx = m - LOW_MIDI + 1
            assert 1 <= idx <= 63, f"note out of range: {tok}"
            out += [idx, ticks]
    out.append(0xFF if loop else 0xFE)
    return out


def ticks_of(text):
    return sum(int(t.split(':')[1]) for t in text.replace('|', ' ').split())


# (name, tempo frames/tick, loop, melody, bass)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import importlib
SONGS = importlib.import_module(os.environ.get("SMS_CONTENT", "content")).SONGS   # tools/content.py


def main():
    os.makedirs(OUT, exist_ok=True)
    periods = []
    for i in range(64):
        m = LOW_MIDI + i - 1
        f = 440.0 * 2 ** ((m - 69) / 12.0)
        p = int(round(CLOCK / (32 * f)))
        periods.append(min(1023, max(1, p)))
    c = ['/* generated by tools/music.py - do not edit */', '#include "music.h"',
         'const unsigned int music_period[64] = {' + ','.join(str(p) for p in periods) + '};']
    table = []
    for name, tempo, loop, mel, bass in SONGS:
        tm, tb = ticks_of(mel), ticks_of(bass)
        if loop:
            assert tm == tb, f"{name}: voices differ in length ({tm} vs {tb})"
        for v, text in (("m", mel), ("b", bass)):
            data = compile_voice(text, loop)
            c.append(f'static const unsigned char {name.lower()}_{v}[] = {{' + ','.join(str(x) for x in data) + '};')
        table.append(f'  {{ {name.lower()}_m, {name.lower()}_b, {tempo} }}')
    c.append('const Song music_songs[] = {\n' + ',\n'.join(table) + '\n};')
    open(os.path.join(OUT, 'music.c'), 'w').write('\n'.join(c) + '\n')
    h = ['/* generated by tools/music.py - do not edit */', '#ifndef MUSIC_H', '#define MUSIC_H',
         'typedef struct { const unsigned char *mel, *bass; unsigned char tempo; } Song;',
         'extern const Song music_songs[];', 'extern const unsigned int music_period[64];']
    for i, s in enumerate(SONGS):
        h.append(f'#define MUS_{s[0]} {i}')
    h += ['#define MUS_NONE 0xFF', '#endif']
    open(os.path.join(OUT, 'music.h'), 'w').write('\n'.join(h) + '\n')
    print(f"{len(SONGS)} songs, {sum(len(compile_voice(s[3], s[2])) + len(compile_voice(s[4], s[2])) for s in SONGS)} bytes of note data")


if __name__ == "__main__":
    main()
